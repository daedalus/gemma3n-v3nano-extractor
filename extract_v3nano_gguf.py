def orientations(ne, ns):
    """How a candidate of normalized shape ns can map onto GGUF dims ne.

    False = same flat order, True = stored transposed. Square 2D tensors
    get both, direct first.
    """
    if len(ne) == 2 and len(ns) == 2:
        out = []
        if ns == ne[::-1]:
            out.append(False)
        if ns == ne:
            out.append(True)
        return out
    if len(ne) in (1, 3):
        return [False] if ns == ne else []
    return []


def source_index(samples, ne, transpose):
    """Flat candidate positions holding GGUF flat positions `samples`."""
    if not transpose:
        return samples
    a, b = ne
    return (samples % a) * b + (samples // a)


def best_candidate(offv, samples, ne, cands):
    """Lowest-MSE candidate for reference values offv: (mse, cand, transpose).

    Candidates are tried in order and ties keep the first one.
    """
    best = (float("inf"), None, False)
    for c in cands:
        for transpose in orientations(ne, c["ns"]):
            try:
                cv = candidate_values(c, source_index(samples, ne, transpose))
            except Exception:
                continue
            d = offv - cv
            mse = float(np.dot(d, d) / d.size)
            if mse < best[0]:
                best = (mse, c, transpose)
    return best


def match_all(reader, by_nelem, nsamp):
    """Per official tensor: lowest-MSE v3nano candidate, plus orientation.

    Replicates the reference matcher exactly (single RNG stream seeded 1234,
    candidates in inventory order, ties keep the first, skip-listed tensors do
    not consume samples), so decisions are reproducible run to run.
    """
    rng = np.random.default_rng(1234)
    decisions = {}
    n_ok = n_fb = 0
    for t in reader.tensors:
        name = t.name
        if name in SKIP_MATCH:
            decisions[name] = {"status": "special"}
            continue
        ne = tuple(int(x) for x in t.shape)
        nelem = 1
        for x in ne:
            nelem *= x
        cands = by_nelem.get(nelem, [])
        if not cands:
            decisions[name] = {"status": "no_candidate"}
            log(f"match {name}: NO CANDIDATE (nelem={nelem})")
            n_fb += 1
            continue
        samples = rng.integers(0, nelem, nsamp, dtype=np.int64)
        offv = official_values(t, samples)
        best = best_candidate(offv, samples, ne, cands)
        mse, c, transpose = best
        if c is None:
            decisions[name] = {"status": "no_shape_match"}
            log(f"match {name}: NO SHAPE MATCH")
            n_fb += 1
            continue
        decisions[name] = dict(
            status="ok", mse=mse, flatbuf=c["path"], sg=c["sg"], ti=c["ti"],
            transpose=bool(transpose), shape=list(c["shape"]), ctype=c["type"],
            hash=c["hash"], offset=c["offset"], nbytes=c["nbytes"],
            scales=c["scales"], zps=c["zps"],
        )
        n_ok += 1
        log(f"match {name}: MSE={mse:.3g} tr={transpose} "
            f"{os.path.basename(c['path'])} sg={c['sg']} ti={c['ti']}")
    log(f"matching done: {n_ok} matched, {n_fb} without usable candidate, "
        f"{len(decisions) - n_ok - n_fb} special")
    return decisions


def _src_record(c, transpose):
    return dict(stem=c["stem"], sg=c["sg"], ti=c["ti"], shape=list(c["shape"]),
                type=c["type"], nbytes=c["nbytes"], transpose=bool(transpose))


def calibrate_map(reader, inv, nsamp, max_mse):
    """Locate every official tensor in the v3nano flatbuffers -> tensor map.

    Unlike match_all this keeps the best candidate whatever its MSE (up to
    max_mse: a v3nano tensor is the right one even when its own int4/int8
    quantization puts it above the strict fallback threshold), also searches
    FLOAT16/UINT8 tensors, stored `1 + w` norms, and 3D tensors stored as
    separate 2D slices. The map only holds flatbuffer coordinates, never
    weights, so it can be committed and reused without the official GGUF.
    """
    by_nelem = group_candidates(inv, INVENTORY_TYPES)
    rng = np.random.default_rng(4321)
    tensors, missing = {}, {}

    def search(offv, samples, ne, nelem):
        cands = by_nelem.get(nelem, [])
        mse, c, tr = best_candidate(offv, samples, ne, cands)
        found = (mse, [(c, tr)] if c is not None else [], 0.0)
        if len(ne) == 3 and cands:
            # stacked [slices, rows, cols] tensor: same flat order as GGUF
            mse3, c3, tr3 = best_candidate(offv, samples, ne[::-1], cands)
            if c3 is not None and mse3 < found[0]:
                found = (mse3, [(c3, False)], 0.0)
        if len(ne) == 1 and cands:          # norm stored as 1 + w
            mse1, c1, tr1 = best_candidate(offv + 1.0, samples, ne, cands)
            if c1 is not None and mse1 < found[0]:
                found = (mse1, [(c1, tr1)], -1.0)
        return found

    for t in reader.tensors:
        name = t.name
        if name == PER_LAYER_NAME:
            continue
        ne = tuple(int(x) for x in t.shape)
        nelem = nelements(ne)
        k = min(nsamp, nelem)
        samples = rng.integers(0, nelem, k, dtype=np.int64)
        offv = official_values(t, samples)
        mse, picks, add = search(offv, samples, ne, nelem)

        if len(ne) == 3 and not (picks and mse < max_mse):
            a, b, nsl = ne                     # try nsl separate 2D slices
            per = a * b
            slice_picks, worst = [], 0.0
            for z in range(nsl):
                ss = rng.integers(0, per, k, dtype=np.int64)
                ov = official_values(t, ss + z * per)
                m, c, tr = best_candidate(ov, ss, (a, b), by_nelem.get(per, []))
                if c is None:
                    slice_picks = None
                    break
                slice_picks.append((c, tr))
                worst = max(worst, m)
            if slice_picks and worst < mse:
                mse, picks, add = worst, slice_picks, 0.0

        if picks and mse < max_mse:
            tensors[name] = dict(mse=mse, add=add,
                                 src=[_src_record(c, tr) for c, tr in picks])
            log(f"map {name}: MSE={mse:.3g} add={add:g} " + ", ".join(
                f"{c['stem']}:{c['sg']}:{c['ti']}{'T' if tr else ''}" for c, tr in picks))
        else:
            missing[name] = None if not picks else mse
            log(f"map {name}: NOT FOUND (best MSE "
                f"{'n/a' if not picks else f'{mse:.3g}'})")
    log(f"map: {len(tensors)} located, {len(missing)} not found in v3nano")
    return dict(format=MAP_FORMAT, chromium_model_version=CHROMIUM_MODEL_VERSION,
                max_mse=max_mse, tensors=tensors, missing=missing)


def load_map_plan(map_path, paths, layout):
    """Build plan from a tensor map: v3nano sources for every tensor."""
    if not os.path.exists(map_path):
        sys.exit(f"ERROR: tensor map not found: {map_path}\n"
                 f"       Create it once with an official GGUF:\n"
                 f"         {os.path.basename(sys.argv[0])} --official "
                 f"<gemma-3n-E2B-it.gguf> --write-map {map_path}")
    tmap = json.load(open(map_path))
    if tmap.get("format") != MAP_FORMAT:
        sys.exit(f"ERROR: {map_path}: unsupported map format {tmap.get('format')}")
    entries = tmap["tensors"]
    plan, missing = {}, []
    for t in layout:
        name = t["name"]
        if name == PER_LAYER_NAME:
            plan[name] = ("per_layer",)
            continue
        e = entries.get(name)
        if e is None:
            il = int(name.split(".")[1]) if name.startswith("blk.") else -1
            if il >= 0 and spec.kv_shared_layer(il) and \
                    name.endswith(("attn_k.weight", "attn_v.weight")):
                # gemma3n reuses K/V of an earlier layer here; llama.cpp never
                # reads these weights, the mobile conversion drops them.
                plan[name] = ("zero", "KV-shared layer, unused")
                continue
            missing.append(name)
            continue
        srcs = []
        for r in e["src"]:
            meta = tflite_tensor_meta(paths[r["stem"]], r["sg"], r["ti"])
            got = (list(meta["shape"]), meta["type"], meta["nbytes"])
            if got != (r["shape"], r["type"], r["nbytes"]):
                sys.exit(f"ERROR: {name}: flatbuffer tensor {r['stem']}:{r['sg']}:"
                         f"{r['ti']} is {got}, map expects "
                         f"{(r['shape'], r['type'], r['nbytes'])} - different "
                         f"Chromium model version?")
            ns = norm_shape(meta["shape"])
            srcs.append(dict(mm=meta["mm"], offset=meta["off"], nbytes=meta["nbytes"],
                             type=meta["type"], shape=meta["shape"], ns=ns,
                             nelem=nelements(ns), scales=meta["scales"],
                             zps=meta["zps"], transpose=r["transpose"]))
        if sum(c["nelem"] for c in srcs) != nelements(t["ne"]):
            sys.exit(f"ERROR: {name}: map sources do not cover ne={t['ne']}")
        plan[name] = ("tflite", srcs, float(e.get("add", 0.0)),
                      f"map mse={e.get('mse', float('nan')):.3g}")
    if missing:
        sys.exit(f"ERROR: {len(missing)} tensor(s) have no v3nano source in "
                 f"{map_path}: {', '.join(missing[:12])}"
                 f"{' ...' if len(missing) > 12 else ''}")
    log(f"map {map_path}: {sum(1 for p in plan.values() if p[0] == 'tflite')} "
        f"v3nano, {sum(1 for p in plan.values() if p[0] == 'zero')} zero-filled, "
        f"1 per-layer assembly")
    return plan


