def verify(new_path, official_path, nsamp=20000):
    """Sampled MSE per tensor: new file vs official. Returns (worst, n_bad)."""
    new_header = parse_gguf_header(new_path)
    ds = new_header["data_start"]
    new_by_name = {t["name"]: t for t in new_header["tensors"]}
    fh = open(new_path, "rb")
    mm = mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ)
    rng = np.random.default_rng(999)
    report = []
    n_bad = 0
    try:
        for t in GGUFReader(official_path).tensors:
            name = t.name
            nt_ = new_by_name.get(name)
            if nt_ is None:
                report.append((float("inf"), name))
                n_bad += 1
                log(f"verify: MISSING {name}")
                continue
            nelem = 1
            for x in nt_["ne"]:
                nelem *= int(x)
            k = min(nsamp, nelem)
            samples = rng.integers(0, nelem, k, dtype=np.int64)
            offv = official_values(t, samples)
            if nt_["type"] == 0:
                newv = buf_view(mm, ds + nt_["offset"], np.float32, nelem)[samples]
            else:
                newv = buf_view(mm, ds + nt_["offset"], np.float16, nelem)[samples].astype(np.float32)
            d = offv - newv
            mse = float(np.dot(d, d) / d.size)
            report.append((mse, name))
            if mse > 1e-3:
                n_bad += 1
                log(f"verify: BAD {name}: MSE={mse:.3g}")
    finally:
        samples = newv = offv = None        # drop mmap views before closing
        try:
            mm.close()
        except BufferError:
            pass
        fh.close()
    report.sort(key=lambda x: -x[0])
    log("verify: worst 10 tensors vs official:")
    for mse, name in report[:10]:
        log(f"verify:   {mse:.4g}  {name}")
    log(f"verify: {len(report)} tensors checked, {n_bad} above 1e-3")
    return report, n_bad


def self_check(new_path, layout, plan, nsamp=20000):
    """Reference-free check: header round-trips, sampled values are finite and
    only intentionally zero-filled tensors are all-zero. Returns n_bad."""
    h = parse_gguf_header(new_path)
    got = [(t["name"], tuple(t["ne"]), t["type"]) for t in h["tensors"]]
    want = [(t["name"], tuple(t["ne"]), 0 if t["type"] == 0 else 1) for t in layout]
    if got != want:
        log("self-check: tensor table differs from the gemma3n layout")
        return 1
    ds = h["data_start"]
    fh = open(new_path, "rb")
    mm = mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ)
    rng = np.random.default_rng(999)
    n_bad = 0
    try:
        for t in h["tensors"]:
            nelem = nelements(t["ne"])
            samples = rng.integers(0, nelem, min(nsamp, nelem), dtype=np.int64)
            dt = np.float32 if t["type"] == 0 else np.float16
            v = buf_view(mm, ds + t["offset"], dt, nelem)[samples].astype(np.float32)
            zero_ok = plan[t["name"]][0] == "zero"
            if not np.all(np.isfinite(v)):
                n_bad += 1
                log(f"self-check: NON-FINITE values in {t['name']}")
            elif not zero_ok and not np.any(v):
                n_bad += 1
                log(f"self-check: {t['name']} is all zeros")
    finally:
        v = samples = None
        try:
            mm.close()
        except BufferError:
            pass
        fh.close()
    log(f"self-check: {len(h['tensors'])} tensors, {n_bad} problem(s)")
    return n_bad


def find_tokenizer(args):
    cands = [args.tokenizer] if args.tokenizer else [
        os.path.join(args.decoded_dir, "TOKENIZER_MODEL.bin"),
        os.path.join(args.flatbuf_dir, "TOKENIZER_MODEL"),
    ]
    for p in cands:
        if p and os.path.exists(p):
            return p
    sys.exit(f"ERROR: SentencePiece tokenizer not found; tried: {', '.join(cands)}\n"
             f"       (stage 0 writes it from weights.bin; or pass --tokenizer)")


