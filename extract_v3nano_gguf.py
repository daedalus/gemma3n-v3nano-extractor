#!/usr/bin/env python3
"""End-to-end v3nano extractor: Chromium bundle -> unquantized GGUF (llama.cpp).

Two modes:

STANDALONE (default, no official GGUF anywhere)
  [0] decode     Chromium `weights.bin` (ZIP-like container; each section's
                 first H bytes XORed with a global 1 MiB keystream, rest clear)
                 -> TF_LITE_*.bin flatbuffers, TOKENIZER_MODEL, METADATA in `dec/`.
  [3] build      KV section generated by gemma3n_spec.py (llama.cpp gemma3n
                 hparams + chat template) with the tokenizer rebuilt from the
                 bundle's SentencePiece TOKENIZER_MODEL; 727 tensor infos from
                 the same spec; every weight streamed from the flatbuffer tensor
                 named in v3nano_tensor_map.json (direct, transposed, stacked
                 2D slices, optional "1 + w" undo). per_layer_token_embd is
                 assembled from its 30 int4 slices. K/V weights of the 10
                 KV-shared layers, which the mobile model does not carry and
                 llama.cpp never reads, are zero-filled.
  [4] check      header round-trip, finite values, no unexpected all-zero tensor.

REFERENCE (--official GGUF; the original pipeline, plus map calibration)
  [1] inventory  mmap every TFLite flatbuffer, index all tensors; identical
                 subgraph copies are collapsed by md5 (raw + scales + zero-points)
                 and shapes are normalized (leading/trailing 1s stripped).
  [2] match      for each official tensor pick the v3nano TFLite tensor with the
                 lowest sampled MSE (20k samples). Orientation:
                     cand.shape == ne         -> stored transposed, gather
                     cand.shape == ne[::-1]   -> same flat order, direct copy
                 kept only if MSE < --threshold (default 5e-5), otherwise the
                 tensor is rebuilt from the official GGUF.
                 --write-map additionally records, for every tensor, where it
                 lives in v3nano (threshold-free up to --map-max-mse) - the
                 tensor map the standalone mode consumes.
  [3] build      KV verbatim from the official GGUF, data as matched/fallback.
  [4] verify     sampled MSE of every tensor vs the official GGUF.

Nothing is materialized whole: TFLite and GGUF data are touched through mmap
views, quantized blocks are dequantized in bounded chunks, and the per-layer
assembly streams 2048-row windows.

Usage (from the repo root):
  python3 extract_v3nano_gguf.py                          # standalone build
  python3 extract_v3nano_gguf.py --decode always          # force re-decode
  python3 extract_v3nano_gguf.py --out /tmp/x.gguf --no-verify
  # one-time calibration of the tensor map against an official GGUF:
  python3 extract_v3nano_gguf.py --official work/bin/gemma-3n-E2B-it-f16.gguf \\
      --write-map v3nano_tensor_map.json

Inputs (canonical layout):
  ~/.cache/gchrome-test-profile/OptGuideOnDeviceModel/*/weights.bin
  work/bin/keystream_1mb.bin          1 MiB XOR keystream
  work/json/encrypt_lengths.json      per-section encrypted header length H
  v3nano_tensor_map.json              GGUF name -> flatbuffer tensor (no weights)

Output: work/bin/v3nano_final.gguf (unquantized).
Quantize separately if needed:
  llama-quantize work/bin/v3nano_final.gguf work/bin/v3nano_final_Q4_K_S.gguf Q4_K_S
"""

